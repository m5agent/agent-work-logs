import assert from 'node:assert/strict';
import {readFile, writeFile} from 'node:fs/promises';
import {resolve, dirname} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const lab = dirname(fileURLToPath(import.meta.url));
const root = resolve(lab, '../..');
const site = resolve(root, '.work/docs-wasm-browser-20261125/head-site');
const json = path => readFile(resolve(site, path)).then(JSON.parse);
const registry = await json('platform/web/uiflow-workbench-profiles.json');
const profiles = await json('platform/web/qemu-browser-profiles.json');
const profile = profiles.profiles.find(row => row.deviceId === 'cardputer-adv');
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const basePath = resolve(lab, 'cardputer-adv-v2.5.3-base.bin');
const baseBytes = await readFile(basePath);
const modulePath = 'platform/runtime/littlefs/littlefs.mjs';
const wasmPath = 'platform/runtime/littlefs/littlefs.wasm';
const manifest = await json('platform/runtime/littlefs/manifest.json');
const moduleBytes = await readFile(resolve(site, modulePath));
const wasmBytes = await readFile(resolve(site, wasmPath));
assert.equal(sha(moduleBytes), manifest.assets.module.sha256);
assert.equal(sha(wasmBytes), manifest.assets.wasm.sha256);
const {default: makeLittlefs} = await import(pathToFileURL(resolve(site, modulePath)));
const engine = await makeLittlefs({wasmBinary:wasmBytes, print() {}, printErr() {}});
const {composeUIFlowWorkbenchImage} = await import(pathToFileURL(resolve(site, 'platform/web/public-uiflow-firmware.js')));
const result = await composeUIFlowWorkbenchImage({profile,registry,baseBytes,engine});
const expected = 'b6255f6af5ad10236380eae09a76b44ca174b5c4de391aef16413bdc590952bd';
assert.equal(result.sha256, expected);
assert.equal(sha(result.bytes), expected);
await writeFile(resolve(lab, 'cardputer-adv-workbench-b6255f6a.bin'), result.bytes, {flag:'wx'});
const receipt = {...result.provenance, firmware_bytes:result.bytes.length, engine_wasm_sha256:sha(wasmBytes), engine_javascript_sha256:sha(moduleBytes)};
await writeFile(resolve(lab, 'firmware-receipt.json'), JSON.stringify(receipt, null, 2) + '\n', {flag:'wx'});
console.log(JSON.stringify(receipt));
